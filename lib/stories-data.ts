export function getStoryBySlug(slug: string) {
  return allStories.find((s) => s.slug === slug) || null;
}

export function getRelatedStories(slug: string, count = 3) {
  const story = getStoryBySlug(slug);
  if (!story) return [];
  return allStories
    .filter((s) => s.slug !== slug && s.category === story.category)
    .slice(0, count);
}
